create table if not exists public.etf_snapshots (
  id bigint generated by default as identity primary key,
  snapshot_date date not null,
  symbol text not null,
  yahoo_symbol text not null,
  name text not null,
  category text not null,
  strategy text not null,
  price numeric,
  etf_score numeric,
  exit_score numeric,
  signal text,
  market_regime text,
  return_20d numeric,
  return_60d numeric,
  return_120d numeric,
  distance_ma20 numeric,
  distance_ma50 numeric,
  distance_ma200 numeric,
  volatility_20d numeric,
  drawdown_from_high numeric,
  average_volume_20d numeric,
  breakdown jsonb not null default '{}'::jsonb,
  reasons jsonb not null default '[]'::jsonb,
  score_version text not null,
  generated_at timestamptz not null default now(),
  unique (snapshot_date, symbol)
);
create index if not exists etf_snapshots_symbol_date_idx on public.etf_snapshots (symbol, snapshot_date desc);
create index if not exists etf_snapshots_score_idx on public.etf_snapshots (snapshot_date desc, etf_score desc);
